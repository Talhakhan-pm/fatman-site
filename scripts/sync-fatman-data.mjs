import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const dataDir = path.resolve(root, "../fatman-data");
const productsCsv = path.join(dataDir, "products.csv");
const fitmentCsv = path.join(dataDir, "fitment.csv");
const outFile = path.join(root, "src/lib/generated-data.ts");

function parseCsv(filePath) {
  const raw = fs.readFileSync(filePath, "utf8").trim();
  const rows = [];
  let current = "";
  let row = [];
  let inQuotes = false;

  for (let i = 0; i < raw.length; i += 1) {
    const char = raw[i];
    const next = raw[i + 1];

    if (char === '"') {
      if (inQuotes && next === '"') {
        current += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (char === "," && !inQuotes) {
      row.push(current);
      current = "";
      continue;
    }

    if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && next === "\n") i += 1;
      row.push(current);
      rows.push(row);
      row = [];
      current = "";
      continue;
    }

    current += char;
  }

  row.push(current);
  rows.push(row);

  const [headers, ...dataRows] = rows;
  return dataRows.map((cols) => {
    const record = {};
    headers.forEach((header, index) => {
      record[header] = cols[index] ?? "";
    });
    return record;
  });
}

const productsRaw = parseCsv(productsCsv);
const fitmentRaw = parseCsv(fitmentCsv);

const products = productsRaw.map((p) => ({
  sku: p.sku,
  slug: p.slug,
  category: p.category,
  brand: p.brand,
  name: p.name,
  shortDescription: p.short_description,
  price: Number(p.price_usd || 0),
  compareAt: p.compare_at_usd ? Number(p.compare_at_usd) : undefined,
  stock:
    p.stock_status === "in_stock"
      ? "in-stock"
      : p.stock_status === "low_stock"
        ? "low-stock"
        : "preorder",
  imageUrl: p.image_url || "",
  shippingClass: p.shipping_class || "ground",
  warrantyDays: Number(p.warranty_days || 0),
  oemPartNumber: p.oem_part_number || "",
}));

const categoryMap = {
  engines: "Long blocks, heads, and complete assemblies.",
  brakes: "Pads, rotors, calipers, lines, and hydraulic service parts.",
  "oem-parts": "Core OEM-style replacement parts across braking, ignition, filtration, intake, and charging systems.",
  drivetrain: "Trans, mounts, and support systems.",
  cooling: "Radiators, thermostats, and flow components.",
  electrical: "Sensors, harnesses, and charging parts.",
  suspension: "Shocks, struts, and ride-control parts.",
};

const categoryTitles = {
  engines: "Engines",
  brakes: "Brakes",
  "oem-parts": "OEM Parts",
  drivetrain: "Drivetrain",
  cooling: "Cooling",
  electrical: "Electrical",
  suspension: "Suspension",
};

const presentCategories = [...new Set(products.map((p) => p.category))];
const categories = presentCategories.map((slug) => ({
  slug,
  title: categoryTitles[slug] ?? slug,
  description: categoryMap[slug] ?? "",
}));

const grouped = {};
for (const row of fitmentRaw) {
  const key = row.product_slug;
  if (!grouped[key]) grouped[key] = {};
  const mt = row.fitment_state === "no-fit" ? "no-fit" : row.fitment_state;
  if (!grouped[key][mt]) grouped[key][mt] = [];
  grouped[key][mt].push({
    year: row.year,
    make: row.make,
    model: row.model,
    engine: row.engine,
  });
}

const fitmentRules = Object.entries(grouped).flatMap(([productSlug, byMatch]) =>
  Object.entries(byMatch).map(([matchType, vehicles]) => ({
    productSlug,
    matchType,
    vehicles,
  })),
);

const years = [...new Set(fitmentRaw.map((r) => r.year))].sort();
const makes = [...new Set(fitmentRaw.map((r) => r.make))].sort();

const modelsByMake = {};
for (const mk of makes) {
  modelsByMake[mk] = [...new Set(fitmentRaw.filter((r) => r.make === mk).map((r) => r.model))].sort();
}

const models = [...new Set(fitmentRaw.map((r) => r.model))];
const enginesByModel = {};
for (const model of models) {
  enginesByModel[model] = [...new Set(fitmentRaw.filter((r) => r.model === model).map((r) => r.engine))].sort();
}

const content = `/* Auto-generated by scripts/sync-fatman-data.mjs */
export const generatedProducts = ${JSON.stringify(products, null, 2)} as const;

export const generatedCategories = ${JSON.stringify(categories, null, 2)} as const;

export const generatedFitmentRules = ${JSON.stringify(fitmentRules, null, 2)} as const;

export const generatedVehicleOptions = ${JSON.stringify(
  { years, makes, modelsByMake, enginesByModel },
  null,
  2,
)} as const;
`;

fs.writeFileSync(outFile, content);
console.log(`Wrote ${outFile}`);
